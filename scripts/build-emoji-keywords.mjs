#!/usr/bin/env node
/**
 * Generates src/emoji/keywords.ts from the Unicode CLDR English emoji
 * annotations (Unicode 15.1 = Twemoji 15.1). Run once, commit the output.
 *
 *   node scripts/build-emoji-keywords.mjs
 */
import { execSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';

const CLDR_VERSION = '45.0.0';
const MAX_EMOJI_PER_WORD = 10; // words attached to more emoji than this are too generic to be useful
const OUT = 'src/emoji/keywords.ts';

const tmp = mkdtempSync(path.join(tmpdir(), 'cldr-'));
execSync(`npm pack cldr-annotations-full@${CLDR_VERSION} --pack-destination "${tmp}" --silent`, { stdio: 'inherit' });
execSync(`tar -xzf "${path.join(tmp, `cldr-annotations-full-${CLDR_VERSION}.tgz`)}" -C "${tmp}" package/annotations/en/annotations.json`);
const data = JSON.parse(readFileSync(path.join(tmp, 'package/annotations/en/annotations.json'), 'utf8'));
const annotations = data.annotations.annotations;

const SKIN_TONE = /[\u{1F3FB}-\u{1F3FF}]/u;
const REGIONAL = /^[\u{1F1E6}-\u{1F1FF}]$/u;
const GENERIC = new Set([
  'face', 'person', 'people', 'symbol', 'sign', 'flag', 'man', 'woman', 'hand', 'mark', 'body', 'gesture',
  'animal', 'nature', 'object', 'food', 'place', 'travel', 'activity', 'emotion', 'button', 'arrow',
  'square', 'circle', 'clock', 'time', 'white', 'black', 'red', 'blue', 'green', 'yellow', 'orange',
  'purple', 'brown', 'large', 'small', 'medium', 'light', 'dark', 'skin', 'tone', 'family', 'couple',
  'letter', 'letters', 'number', 'numbers', 'input', 'keycap', 'regional', 'indicator', 'and', 'or',
  'of', 'the', 'with', 'in', 'on', 'a', 'an', 'to', 'up', 'down', 'left', 'right', 'no', 'not',
]);

// Code points that Twemoji names with a trailing FE0F inside ZWJ sequences (e.g. ❤️‍🔥, 🏳️‍🌈, 👮‍♂️).
const NEEDS_VS16 = new Set([0x2764, 0x1f3f3, 0x1f441, 0x1f5e8, 0x2640, 0x2642, 0x2620, 0x2695, 0x2696, 0x2708, 0x26a7]);
function qualify(emoji) {
  const cps = Array.from(emoji, (ch) => ch.codePointAt(0));
  if (!cps.includes(0x200d)) return emoji;
  const out = [];
  cps.forEach((cp, i) => {
    out.push(cp);
    if (NEEDS_VS16.has(cp) && cps[i + 1] !== 0xfe0f) out.push(0xfe0f);
  });
  return String.fromCodePoint(...out);
}

const wordToEmoji = new Map();
for (const [rawEmoji, entry] of Object.entries(annotations)) {
  if (SKIN_TONE.test(rawEmoji) || REGIONAL.test(rawEmoji)) continue;
  if (rawEmoji.length > 20) continue;
  const emoji = qualify(rawEmoji);
  const phrases = [...(entry.default ?? []), ...(entry.tts ?? [])];
  const words = new Set();
  for (const phrase of phrases) {
    const clean = phrase.toLowerCase().replace(/[^a-z0-9\s'-]/g, ' ').replace(/'/g, '').trim();
    if (!clean) continue;
    const parts = clean.split(/\s+/).filter(Boolean);
    if (parts.length >= 2 && parts.length <= 3) words.add(parts.join(' '));
    for (const part of parts) if (part.length >= 3) words.add(part);
  }
  for (const word of words) {
    if (GENERIC.has(word)) continue;
    const list = wordToEmoji.get(word) ?? [];
    if (!list.includes(emoji)) list.push(emoji);
    wordToEmoji.set(word, list);
  }
}

const entries = [...wordToEmoji.entries()]
  .filter(([, list]) => list.length <= MAX_EMOJI_PER_WORD)
  .sort(([a], [b]) => (a < b ? -1 : 1));

const lines = entries.map(([word, list]) => `  ${JSON.stringify(word)}: ${JSON.stringify(list.slice(0, 6))},`);
const source = `// Generated by scripts/build-emoji-keywords.mjs from CLDR ${CLDR_VERSION} English emoji
// annotations (Unicode license, https://www.unicode.org/license.txt). Do not edit by hand.

/** Words and short phrases from the Unicode emoji annotations, mapped to the emoji they describe. */
export const EMOJI_KEYWORDS: Readonly<Record<string, readonly string[]>> = {
${lines.join('\n')}
};
`;
writeFileSync(OUT, source);
console.log(`Wrote ${OUT}: ${entries.length} words/phrases (${(source.length / 1024).toFixed(0)} KB)`);
